def return_mapping_viscoplasticity(eps_n, sig_n, d_eps, dt, eps_vp_n, E, sigma_y, eta, n=1):
    """
    1D viscoplastic return mapping (Perzyna model)
    UMAT-style interface with support for general exponent n
    
    Parameters:
    -----------
    eps_n : float
        Total strain at step n
    sig_n : float
        Stress at step n [MPa]
    d_eps : float
        Strain increment (eps_{n+1} - eps_n)
    dt : float
        Time increment [s]
    eps_vp_n : float
        Viscoplastic strain at step n
    E : float
        Young's modulus [MPa]
    sigma_y : float
        Yield stress [MPa]
    eta : float
        Viscosity [MPa·s]
    n : int or float, optional
        Rate sensitivity exponent (default=1)
        n=1: Linear Perzyna (closed-form solution)
        n>1: Nonlinear (requires Newton-Raphson iteration)
    
    Returns:
    --------
    sigma_np1 : float
        Stress at step n+1 [MPa]
    eps_vp_np1 : float
        Viscoplastic strain at step n+1
    
    Notes:
    ------
    - For n=1, uses closed-form solution (no iteration required)
    - For n≠1, uses Newton-Raphson to solve nonlinear equation
    - Implements backward Euler time integration (unconditionally stable)
    """
    
    # 1. Update total strain
    eps_np1 = eps_n + d_eps
    
    # 2. Elastic predictor (trial stress)
    sigma_trial = E * (eps_np1 - eps_vp_n)
    
    # 3. Check yield condition
    f_trial = abs(sigma_trial) - sigma_y
    
    if f_trial <= 0:
        # Elastic step - no viscoplastic flow
        sigma_np1 = sigma_trial
        eps_vp_np1 = eps_vp_n
        
        return sigma_np1, eps_vp_np1
    
    else:
        # Viscoplastic step - compute plastic multiplier
        
        if abs(n - 1.0) < 1e-10:
            # Linear case (n=1): closed-form solution
            d_lambda = _compute_dlambda_linear(f_trial, dt, E, sigma_y, eta)
        else:
            # Nonlinear case (n≠1): Newton-Raphson iteration
            d_lambda = _compute_dlambda_nonlinear(f_trial, dt, E, sigma_y, eta, n)
        
        # 4. Update viscoplastic strain
        eps_vp_np1 = eps_vp_n + d_lambda * np.sign(sigma_trial)
        
        # 5. Update stress (return toward yield surface)
        sigma_np1 = sigma_trial - E * d_lambda * np.sign(sigma_trial)
        
        return sigma_np1, eps_vp_np1


def _compute_dlambda_linear(f_trial, dt, E, sigma_y, eta):
    """
    Compute plastic multiplier for linear Perzyna (n=1)
    Closed-form solution (no iteration needed)
    
    Parameters:
    -----------
    f_trial : float
        Trial yield function (overstress) [MPa]
    dt : float
        Time increment [s]
    E : float
        Young's modulus [MPa]
    sigma_y : float
        Yield stress [MPa]
    eta : float
        Viscosity [MPa·s]
    
    Returns:
    --------
    d_lambda : float
        Plastic multiplier increment
    """
    # For n=1, the equation is linear:
    # Δλ = (Δt/η) * (f_trial/σy) / (1 + Δt*E/(η*σy))
    # 
    # Simplified (multiply by σy):
    # Δλ = Δt*f_trial / (η + Δt*E)
    
    d_lambda = (dt * f_trial) / (eta + dt * E)
    
    return d_lambda


def _compute_dlambda_nonlinear(f_trial, dt, E, sigma_y, eta, n, 
                                 max_iter=20, tol=1e-10):
    """
    Compute plastic multiplier for nonlinear Perzyna (n≠1)
    Uses Newton-Raphson iteration to solve nonlinear equation
    
    Parameters:
    -----------
    f_trial : float
        Trial yield function (overstress) [MPa]
    dt : float
        Time increment [s]
    E : float
        Young's modulus [MPa]
    sigma_y : float
        Yield stress [MPa]
    eta : float
        Viscosity [MPa·s]
    n : float
        Rate sensitivity exponent
    max_iter : int, optional
        Maximum Newton-Raphson iterations (default=20)
    tol : float, optional
        Convergence tolerance (default=1e-10)
    
    Returns:
    --------
    d_lambda : float
        Plastic multiplier increment
    
    Notes:
    ------
    Solves: Δλ = (Δt/η) * ((f_trial - E*Δλ)/σy)^n
    Using Newton-Raphson on residual:
        R(Δλ) = Δλ - (Δt/η) * ((f_trial - E*Δλ)/σy)^n = 0
    """
    
    # Initial guess: use linearized approximation
    # (one Newton step from Δλ=0)
    numerator = (dt / eta) * (f_trial / sigma_y)**n
    denominator = 1.0 + n * (dt * E) / (eta * sigma_y**n) * f_trial**(n-1)
    d_lambda = numerator / denominator
    
    # Newton-Raphson iteration
    for iteration in range(max_iter):
        # Current overstress after return
        f_current = f_trial - E * d_lambda
        
        # Safety check: overstress should remain positive
        if f_current < 0:
            # Overshot - use smaller Δλ
            d_lambda *= 0.5
            continue
        
        # Residual: R(Δλ) = Δλ - (Δt/η) * (f_current/σy)^n
        R = d_lambda - (dt / eta) * (f_current / sigma_y)**n
        
        # Derivative: dR/dΔλ = 1 + n*(Δt*E)/(η*σy^n) * (f_current/σy)^(n-1)
        dR_ddlambda = 1.0 + n * (dt * E) / (eta * sigma_y**n) * \
                      (f_current / sigma_y)**(n - 1)
        
        # Newton-Raphson update
        d_lambda_new = d_lambda - R / dR_ddlambda
        
        # Check for negative Δλ (shouldn't happen, but safety check)
        if d_lambda_new < 0:
            d_lambda_new = d_lambda * 0.5
        
        # Check convergence
        if abs(d_lambda_new - d_lambda) < tol:
            return d_lambda_new
        
        # Update for next iteration
        d_lambda = d_lambda_new
        
        if iteration == max_iter-1:
            # If we reach here, convergence failed
            print(f"Warning: Newton-Raphson did not converge in {max_iter} iterations")
            print(f"  Final residual: {np.abs(R):.6e}")
            print(f"  Returning current value: Δλ = {d_lambda:.6e}")
    


    
    return d_lambda

def test_rate_sensitivity():
    """
    Load to eps=0.003 at three different strain rates
    Steel-like material
    """
    # Material properties - STEEL
    E = 200e3  # MPa (200 GPa)
    sigma_y = 250  # MPa
    eta = 40e3  # MPa·s (40 GPa·s) - CORRECTED UNITS
    n = 1
    
    print("Material: Steel-like")
    print(f"E = {E/1e3:.0f} GPa")
    print(f"σy = {sigma_y:.0f} MPa")
    print(f"η = {eta/1e3:.0f} GPa·s")
    print()
    
    # Three loading rates
    strain_rates = [0.001, 0.01, 0.1]  # /s
    rate_labels = ['Slow (0.001/s)', 'Medium (0.01/s)', 'Fast (0.1/s)']
    
    max_strain = 0.003
    dt = 0.01  # s - Fixed time step
    
    results = []
    
    for strain_rate in strain_rates:
        # Calculate number of steps
        total_time = max_strain / strain_rate
        n_steps = int(total_time / dt)
        d_eps = strain_rate * dt
        
        # Initialize state
        eps_n = 0.0
        sig_n = 0.0
        eps_vp_n = 0.0
        
        # Storage
        strain_history = [0.0]
        stress_history = [0.0]
        
        # Time integration
        for step in range(n_steps):
            sigma_np1, eps_vp_np1 = return_mapping_viscoplasticity(
                eps_n, sig_n, d_eps, dt, eps_vp_n, E, sigma_y, eta, n
            )
            
            # Update state
            eps_n += d_eps
            sig_n = sigma_np1
            eps_vp_n = eps_vp_np1
            
            # Store
            strain_history.append(eps_n)
            stress_history.append(sig_n)
        
        results.append((strain_history, stress_history))
    
    # Plot
    plt.figure(figsize=(10, 6))
    for i, (eps_hist, sig_hist) in enumerate(results):
        plt.plot(eps_hist, sig_hist, marker='o', markevery=max(1, len(eps_hist)//20), 
                label=rate_labels[i])
    
    plt.axhline(y=sigma_y, color='r', linestyle='--', alpha=0.5, label='Yield stress')
    plt.xlabel('Strain')
    plt.ylabel('Stress [MPa]')
    plt.title('Rate Sensitivity Test (Steel, η=40 GPa·s)')
    plt.legend()
    plt.grid(True, alpha=0.3)
    plt.savefig('week03_rate_sensitivity.png', dpi=150, bbox_inches='tight')
    plt.show()
    
    # Report peak stresses
    print("\nResults:")
    for i, (_, sig_hist) in enumerate(results):
        peak = max(sig_hist)
        print(f"{rate_labels[i]}: Peak stress = {peak:.2f} MPa")
    
    # Calculate rate sensitivity
    slow_peak = max(results[0][1])
    fast_peak = max(results[2][1])
    rate_sensitivity = (fast_peak - slow_peak) / slow_peak * 100
    print(f"\nRate sensitivity: {rate_sensitivity:.1f}% increase from slow to fast")

def test_creep():
    """
    Creep test: Apply constant stress, measure strain evolution
    
    Uses direct integration of viscoplastic flow rule.
    This is appropriate for constant stress conditions where
    we can analytically integrate the constitutive equations.
    
    Note: In real FEM, this would be handled by load control boundary
    conditions, but the constitutive update would still be strain-driven
    at the Gauss point level. This test isolates the material response.
    """
    import numpy as np
    import matplotlib.pyplot as plt
    
    # Material properties - STEEL
    E = 200e3  # MPa (200 GPa)
    sigma_y = 250  # MPa
    eta = 40e3  # MPa·s (40 GPa·s)
    n = 1  # Linear Perzyna
    
    print("="*70)
    print("                        CREEP TEST")
    print("="*70)
    print(f"Material Properties:")
    print(f"  Young's modulus: E = {E/1e3:.0f} GPa")
    print(f"  Yield stress: σy = {sigma_y:.0f} MPa")
    print(f"  Viscosity: η = {eta/1e3:.0f} GPa·s")
    print(f"  Rate exponent: n = {n}")
    print()
    
    # Test parameters
    sigma_applied = 270  # MPa (constant stress, above yield)
    T_MAX = 1000  # seconds
    DT = 10.0  # time step [s]
    
    overstress = sigma_applied - sigma_y
    print(f"Test Conditions:")
    print(f"  Applied stress: σ = {sigma_applied:.0f} MPa (constant)")
    print(f"  Overstress: f = {overstress:.0f} MPa")
    print(f"  Duration: T = {T_MAX:.0f} s")
    print(f"  Time step: Δt = {DT:.1f} s")
    print()
    
    # Theoretical predictions
    f = sigma_applied - sigma_y
    eps_vp_dot_theory = (1.0 / eta) * (f / sigma_y)  # Steady-state creep rate
    
    print(f"Theoretical Predictions (n=1, constant stress):")
    print(f"  Viscoplastic strain rate: ε̇ᵛᵖ = {eps_vp_dot_theory:.6e} /s")
    print(f"  Total viscoplastic strain (t={T_MAX}s): εᵛᵖ = {eps_vp_dot_theory * T_MAX:.6e}")
    print()
    
    # =========================================================================
    # DIRECT INTEGRATION OF VISCOPLASTIC FLOW RULE
    # =========================================================================
    
    # Initialize state variables
    t = 0.0
    eps_vp = 0.0  # Initial viscoplastic strain
    eps_total = sigma_applied / E  # Initial elastic strain
    
    # Storage arrays
    time_history = [0.0]
    eps_total_history = [eps_total]
    eps_vp_history = [0.0]
    stress_history = [sigma_applied]
    
    print("Time Integration:")
    print(f"{'Time [s]':>10} {'ε_total':>15} {'ε_vp':>15} {'σ [MPa]':>12} {'ε̇_vp [/s]':>15}")
    print("-"*70)
    
    step = 0
    while t < T_MAX:
        t += DT
        step += 1
        
        # =====================================================================
        # For constant stress above yield, viscoplastic strain rate is constant
        # =====================================================================
        
        # Overstress (constant)
        f = sigma_applied - sigma_y  # = 20 MPa
        
        # Viscoplastic strain rate (Perzyna model, n=1)
        eps_vp_dot = (1.0 / eta) * (f / sigma_y)
        
        # Update viscoplastic strain (backward Euler)
        d_eps_vp = eps_vp_dot * DT
        eps_vp += d_eps_vp
        
        # Update total strain to maintain constant stress
        # From: σ = E(ε_total - ε_vp) = constant
        # Therefore: ε_total = σ/E + ε_vp
        eps_total = sigma_applied / E + eps_vp
        
        # Stress remains exactly constant (by construction)
        stress = sigma_applied
        
        # Store results
        time_history.append(t)
        eps_total_history.append(eps_total)
        eps_vp_history.append(eps_vp)
        stress_history.append(stress)
        
        # Print every 10 steps
        if step % 10 == 0:
            print(f"{t:10.1f} {eps_total:15.6e} {eps_vp:15.6e} {stress:12.2f} {eps_vp_dot:15.6e}")
    
    print()
    print("="*70)
    
    # =========================================================================
    # POST-PROCESSING AND ANALYSIS
    # =========================================================================
    
    # Convert to arrays for analysis
    time_array = np.array(time_history)
    eps_total_array = np.array(eps_total_history)
    eps_vp_array = np.array(eps_vp_history)
    stress_array = np.array(stress_history)
    
    # Calculate creep rate (numerical derivative)
    creep_rate = np.gradient(eps_total_array, time_array)
    
    # Final results
    eps_vp_final = eps_vp_history[-1]
    eps_total_final = eps_total_history[-1]
    creep_rate_final = creep_rate[-1]
    
    # Errors
    eps_vp_error = abs(eps_vp_final - eps_vp_dot_theory * T_MAX) / (eps_vp_dot_theory * T_MAX) * 100
    creep_rate_error = abs(creep_rate_final - eps_vp_dot_theory) / eps_vp_dot_theory * 100
    
    print("RESULTS:")
    print()
    print("Strain Evolution:")
    print(f"  Initial total strain: ε₀ = {eps_total_history[0]:.6e}")
    print(f"  Final total strain: ε(T) = {eps_total_final:.6e}")
    print(f"  Strain increase: Δε = {eps_total_final - eps_total_history[0]:.6e}")
    print()
    print("Viscoplastic Strain:")
    print(f"  Numerical: εᵛᵖ(T) = {eps_vp_final:.6e}")
    print(f"  Theoretical: εᵛᵖ(T) = {eps_vp_dot_theory * T_MAX:.6e}")
    print(f"  Error: {eps_vp_error:.4f}%")
    print()
    print("Creep Rate:")
    print(f"  Numerical (final): ε̇ᵛᵖ = {creep_rate_final:.6e} /s")
    print(f"  Theoretical: ε̇ᵛᵖ = {eps_vp_dot_theory:.6e} /s")
    print(f"  Error: {creep_rate_error:.4f}%")
    print()
    print("Stress Control:")
    print(f"  Target: {sigma_applied:.2f} MPa")
    print(f"  Mean: {np.mean(stress_array):.2f} MPa")
    print(f"  Std dev: {np.std(stress_array):.6f} MPa")
    print(f"  Max deviation: {np.max(np.abs(stress_array - sigma_applied)):.6f} MPa")
    print()
    print("="*70)
    
    # =========================================================================
    # PLOTTING
    # =========================================================================
    
    fig, axes = plt.subplots(2, 2, figsize=(14, 10))
    
    # Plot 1: Total strain vs time (primary creep curve)
    ax1 = axes[0, 0]
    ax1.plot(time_history, eps_total_history, 'b-', linewidth=2.5, label='Total strain (numerical)')
    ax1.plot(time_history, eps_vp_history, 'g--', linewidth=2, label='Viscoplastic strain')
    
    # Add theoretical line
    eps_elastic = sigma_applied / E
    strain_theory = eps_elastic + eps_vp_dot_theory * time_array
    ax1.plot(time_array, strain_theory, 'k:', linewidth=2, alpha=0.6, label='Theoretical (ε = σ/E + ε̇ᵛᵖ·t)')
    
    ax1.set_xlabel('Time [s]', fontsize=12, fontweight='bold')
    ax1.set_ylabel('Strain', fontsize=12, fontweight='bold')
    ax1.set_title('Creep Curve: Strain vs Time', fontsize=13, fontweight='bold')
    ax1.legend(fontsize=10)
    ax1.grid(True, alpha=0.3)
    
    # Plot 2: Stress vs time (should be perfectly constant)
    ax2 = axes[0, 1]
    ax2.plot(time_history, stress_history, 'r-', linewidth=2.5, label='Applied stress')
    ax2.axhline(y=sigma_applied, color='k', linestyle='--', linewidth=1.5, 
                alpha=0.5, label=f'Target: {sigma_applied} MPa')
    ax2.axhline(y=sigma_y, color='orange', linestyle=':', linewidth=1.5,
                alpha=0.7, label=f'Yield: {sigma_y} MPa')
    
    ax2.set_xlabel('Time [s]', fontsize=12, fontweight='bold')
    ax2.set_ylabel('Stress [MPa]', fontsize=12, fontweight='bold')
    ax2.set_title('Applied Stress (Constant)', fontsize=13, fontweight='bold')
    ax2.set_ylim([sigma_y - 10, sigma_applied + 10])
    ax2.legend(fontsize=10)
    ax2.grid(True, alpha=0.3)
    
    # Plot 3: Creep rate vs time
    ax3 = axes[1, 0]
    ax3.plot(time_history, creep_rate, 'm-', linewidth=2.5, label='Numerical (dε/dt)')
    ax3.axhline(y=eps_vp_dot_theory, color='k', linestyle='--', linewidth=1.5,
                alpha=0.6, label=f'Theoretical: {eps_vp_dot_theory:.2e} /s')
    
    ax3.set_xlabel('Time [s]', fontsize=12, fontweight='bold')
    ax3.set_ylabel('Creep Rate [1/s]', fontsize=12, fontweight='bold')
    ax3.set_title('Creep Rate (should be constant)', fontsize=13, fontweight='bold')
    ax3.ticklabel_format(axis='y', style='scientific', scilimits=(0,0))
    ax3.legend(fontsize=10)
    ax3.grid(True, alpha=0.3)
    ax3.set_ylim([0, eps_vp_dot_theory * 1.5])
    
    # Plot 4: Strain components breakdown
    ax4 = axes[1, 1]
    eps_elastic_history = stress_array / E
    ax4.plot(time_history, eps_total_history, 'b-', linewidth=2.5, label='Total strain')
    ax4.plot(time_history, eps_vp_history, 'g-', linewidth=2, label='Viscoplastic strain')
    ax4.plot(time_history, eps_elastic_history, 'c-', linewidth=2, label='Elastic strain')
    
    ax4.set_xlabel('Time [s]', fontsize=12, fontweight='bold')
    ax4.set_ylabel('Strain', fontsize=12, fontweight='bold')
    ax4.set_title('Strain Decomposition: ε = εᵉ + εᵛᵖ', fontsize=13, fontweight='bold')
    ax4.legend(fontsize=10)
    ax4.grid(True, alpha=0.3)
    
    plt.tight_layout()
    plt.savefig('week03_creep.png', dpi=150, bbox_inches='tight')
    plt.show()
    
    print("Plot saved: week03_creep.png")
    print()

def test_relaxation():
    """
    Apply strain suddenly, hold constant, measure stress decay
    Steel-like material
    """
    # Material properties - STEEL
    E = 200e3  # MPa
    sigma_y = 250  # MPa
    eta = 40e3  # MPa·s (40 GPa·s)
    n = 1
    
    print("Relaxation Test - Steel")
    print(f"η = {eta/1e3:.0f} GPa·s")
    
    # Test parameters
    eps_applied = 0.002  # Applied strain (held constant)
    T_MAX = 100  # seconds
    DT = 10.0  # s
    
    print(f"Applied strain: {eps_applied:.4f} (held constant)")
    print(f"Time duration: {T_MAX} s")
    print()
    
    # Step 1: Apply strain instantaneously
    eps_n = 0.0
    sig_n = 0.0
    eps_vp_n = 0.0
    d_eps_initial = eps_applied
    dt_initial = 0.01  # Small time step (quasi-instantaneous)
    
    sigma_np1, eps_vp_np1 = return_mapping_viscoplasticity(
        eps_n, sig_n, d_eps_initial, dt_initial, eps_vp_n, E, sigma_y, eta, n
    )
    
    # Update state after loading
    eps_n = eps_applied
    sig_n = sigma_np1
    eps_vp_n = eps_vp_np1
    
    print(f"Initial stress (t=0+): {sig_n:.2f} MPa")
    
    # Storage
    time_history = [0.0]
    stress_history = [sig_n]
    strain_history = [eps_n]
    
    # Step 2: Hold strain constant, let stress relax
    t = 0.0
    while t < T_MAX:
        t += DT
        
        # No additional strain (strain held constant)
        d_eps = 0.0
        
        # Call return mapping
        sigma_np1, eps_vp_np1 = return_mapping_viscoplasticity(
            eps_n, sig_n, d_eps, DT, eps_vp_n, E, sigma_y, eta, n
        )
        
        # Update state
        sig_n = sigma_np1
        eps_vp_n = eps_vp_np1
        # eps_n stays constant
        
        # Store
        time_history.append(t)
        stress_history.append(sig_n)
        strain_history.append(eps_n)
    
    # Plot
    plt.figure(figsize=(10, 6))
    plt.plot(time_history, stress_history, 'b-', linewidth=2)
    plt.axhline(y=sigma_y, color='r', linestyle='--', linewidth=2, 
                alpha=0.7, label=f'Yield stress ({sigma_y} MPa)')
    plt.xlabel('Time [s]')
    plt.ylabel('Stress [MPa]')
    plt.title(f'Relaxation Test: ε = {eps_applied:.4f} (constant)')
    plt.legend()
    plt.grid(True, alpha=0.3)
    plt.savefig('week03_relaxation.png', dpi=150, bbox_inches='tight')
    plt.show()
    
    print(f"\nInitial stress (t=0): {stress_history[0]:.2f} MPa")
    print(f"Final stress (t={T_MAX}s): {stress_history[-1]:.2f} MPa")
    print(f"Stress drop: {stress_history[0] - stress_history[-1]:.2f} MPa")
    print(f"Distance from yield: {abs(stress_history[-1] - sigma_y):.2f} MPa")

